// One-off converter: stars.json -> js/data-stars.js
// The game runs off file:// where fetch() is blocked, so star data ships
// as a plain script. Rerun after regenerating stars.json:
//   node tools/convert-stars.js
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var data = JSON.parse(fs.readFileSync(path.join(root, 'stars.json'), 'utf8'));

var out = '// GENERATED by tools/convert-stars.js from stars.json — do not edit.\n' +
          'window.TW_STARS = ' + JSON.stringify(data) + ';\n';

fs.writeFileSync(path.join(root, 'js', 'data-stars.js'), out);
console.log('wrote js/data-stars.js  (' + data.stars.length + ' stars)');
